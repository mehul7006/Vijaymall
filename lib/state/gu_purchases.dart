/// Sentence patterns built from a label ([t] translates it) that have no
/// fixed key: validator messages of `Validators.text` and friends.
String? guPurchasesDynamic(String en, String Function(String) t) {
  var m = RegExp(r'^(.+) is required$').firstMatch(en);
  if (m != null) return '${t(m.group(1)!)} જરૂરી છે';
  m = RegExp(r'^(.+) must be (\d+) characters or fewer$').firstMatch(en);
  if (m != null) return '${t(m.group(1)!)} વધુમાં વધુ ${m.group(2)} અક્ષરનું હોય';
  m = RegExp(r'^(.+) must be a whole number$').firstMatch(en);
  if (m != null) return '${t(m.group(1)!)} પૂર્ણ સંખ્યા હોવી જોઈએ';
  m = RegExp(r'^(.+) must be (\d+) or less$').firstMatch(en);
  if (m != null) return '${t(m.group(1)!)} ${m.group(2)} કે તેથી ઓછું હોવું જોઈએ';
  return null;
}
