/// Central English -> Gujarati lookup for shared widgets (buttons, toasts,
/// sheet titles, field labels, pills, empty states). Screens that already use
/// the inline `gu ? 'ગુજરાતી' : 'English'` pattern are unaffected; strings with
/// no entry here pass through unchanged.
class GuLang {
  GuLang._();

  /// Mirrors `AppState.lang == 'gu'`; kept in sync by `AppState.setLang`.
  static bool active = false;
}

/// Returns the Gujarati text for [en] when Gujarati is active, else [en].
String gt(String en) {
  if (!GuLang.active) return en;
  final hit = _gu[en];
  if (hit != null) return hit;
  final fl = guFlash[en];
  if (fl != null) return fl;
  final gb = guBank[en] ?? kGuAuditFix[en] ?? guTillfix[en] ?? guBankfix[en] ?? guGst[en] ?? guGst2[en] ?? guCore10[en] ?? guCore20[en] ?? guCore40[en] ?? guP1[en] ?? guLots[en] ?? guLabels[en] ?? guCounter[en] ?? guPurchases[en] ?? guCore[en];
  if (gb != null) return gb;
  final pu = guPush[en];
  if (pu != null) return pu;
  final st = guStore[en];
  if (st != null) return st;
  final sh = guShell[en];
  if (sh != null) return sh;
  final fi = guFilters[en];
  if (fi != null) return fi;
  final hb = guHotbuy[en];
  if (hb != null) return hb;
  final fu = guFollowup[en];
  if (fu != null) return fu;
  final pd = guPurchasesDynamic(en, gt);
  if (pd != null) return pd;
  final pf = guPosfix[en] ?? guPosfixDynamic(en);
  if (pf != null) return pf;
  for (final p in _prefixes) {
    if (en.startsWith(p.$1)) return p.$2 + en.substring(p.$1.length);
  }
  if (en.startsWith('Order ') && en.endsWith(' placed')) {
    return 'ઓર્ડર ${en.substring(6, en.length - 7)} મૂકાયો';
  }
  final left = RegExp(r'^Only (\d+) left$').firstMatch(en);
  if (left != null) return 'ફક્ત ${left.group(1)} બાકી';
  final nLeft = RegExp(r'^(\d+) left$').firstMatch(en);
  if (nLeft != null) return '${nLeft.group(1)} બાકી';
  for (final s in _suffixes) {
    if (en.endsWith(s.$1)) return en.substring(0, en.length - s.$1.length) + s.$2;
  }
  return en;
}

